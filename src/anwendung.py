def summe(a, b):
    """Gibt die Summe von a und b zurück."""
    return a + b

def differenz(a, b):
    """"Gibt die Differenz von a und b zurück."""
    return a - b

def prozent(a, b):
    """"Gibt die Prozent von a zu b zurück."""
    return a / b * 100

def multiplikation(a, b):
    """"Gibt die Multiplikation von a * b zurück."""
    return a * b

